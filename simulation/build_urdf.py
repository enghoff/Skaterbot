# requires-python = ">=3.11,<3.13"
# dependencies = ["numpy>=1.26", "trimesh>=4.0", "scipy>=1.11",
#                 "networkx>=3.0", "manifold3d>=2.3", "build123d>=0.9"]
# ///
"""Write the URDF, and the meshes it points at, from the CAD.

    uv run simulation/build_urdf.py

Free and offline, and so is the STL export it reads, which used to be the one
metered step in the pipeline:

    uv run tools/export.py --format stl --out simulation/meshes

Run that whenever a printed part changes shape. Everything after it -- masses,
centres of mass, inertia tensors, the kinematic tree, the URDF itself -- is
computed here.

WHAT COMES OUT

    simulation/urdf/wheeled_biped.urdf     the robot
    simulation/urdf/meshes/*.stl           binary copies of the export

The meshes are rewritten as binary because the exporter emits ASCII STL, which
is about five times the size for the same triangles, and these are tracked in git
so that a checkout can be simulated without rebuilding them.

WHAT IS IN HERE. The whole robot, not only the printed parts: every solid
simulation/robot.py gives a link is written out as a visual as well as folded
into that link's inertia, so the actuators, the wheels, the bearings and the
boards are geometry in the file rather than anonymous mass. The primitive drawn
is the same one the inertia was integrated from, which is the point -- a picture
that disagrees with the physics would be worse than no picture.

WHAT IS NOT IN HERE. No contact parameters, no actuator gains, no armature.
Those are simulator settings rather than descriptions of the robot, and they
live in simulation/isaaclab/wheeled_biped_cfg.py where Isaac Lab can read them.
A URDF is the mechanism; it is not the plant.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import trimesh

sys.path.insert(0, str(Path(__file__).resolve().parent))

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import robot as robot_model  # noqa: E402
from inertia import (  # noqa: E402
    MeshLibrary,
    is_plausible,
    link_properties,
    ros_point,
    rpy_from_axis_x,
    to_si,
)

from cad.dimensions import closure  # noqa: E402
from cad.dimensions import colors as load_colors

HERE = Path(__file__).resolve().parent
URDF_DIR = HERE / "urdf"
URDF_MESHES = URDF_DIR / "meshes"
RAW_MESHES = HERE / "meshes"

ROBOT_NAME = "wheeled_biped"

# How much newer a CAD file may be than the mesh it built before the mesh is
# called stale. A checkout touches everything at once, so a couple of seconds
# of slack keeps that from firing on every fresh clone.
GRACE_SECONDS = 2.0


def vec(values) -> str:
    return " ".join(f"{float(v):.9g}" for v in values)


def comment(text: str) -> str:
    """Wrap prose in an XML comment, having made it legal to put there.

    XML forbids a double hyphen inside a comment, and this project writes them
    everywhere -- it is the house dash. A strict parser rejects the whole file
    over one, so they become en dashes on the way out. The delimiters are added
    here rather than by the caller, so that sanitising the prose can never
    reach them.
    """
    return f"<!--{text.replace('--', '–')}-->"


def materials_block(materials: dict[str, tuple[float, float, float]]) -> str:
    """One URDF material per CAD colour the robot actually uses."""
    return "".join(
        f'  <material name="{name}"><color rgba="{vec(rgb)} 1"/></material>\n'
        for name, rgb in sorted(materials.items())
    )


def header(dimensions: dict[str, float], materials: dict) -> str:
    """The provenance block, so the file says what it is without a reader."""
    actuator = robot_model.ACTUATOR
    palette = comment(
        " Colours are the CAD's own, read out of cad/parameters.py and"
        " cad/electronics.py by cad.dimensions.colors, so a part is the same"
        " colour here as it is in the CAD viewer. "
    )
    return (
        '<?xml version="1.0"?>\n'
        + comment(f"""
  GENERATED by simulation/build_urdf.py. Do not edit this file: edit the CAD,
  or edit simulation/robot.py, and regenerate.

  The compact torque-controlled WHEELED biped -- six DM-J3507 actuators, hip
  pitch and knee and a driven wheel on each leg, and no hip roll at all. The
  eight-motor walking robot is a different machine and is not described here.

  FRAME. +X forward, +Y left, +Z up, the ROS convention. The CAD is drawn with
  +Y forward and +X to the robot's right, so everything here has been turned a
  quarter turn from the frame the CAD and the mesh files use.

  BASE. base_link's origin is the torso's centre, {dimensions["wheeledTorsoCenterHeight"] / 1000.0:.4f} m above the
  ground in the neutral standing pose. The robot stands {dimensions["wheeledTorsoTop"] / 1000.0:.3f} m tall and its
  wheels are {dimensions["skateWheelCenterX"] * 2.0 / 1000.0 + dimensions["hipSpacing"] / 1000.0:.4f} m apart at the contact patch.

  JOINT SIGNS. Both leg joints are positive in FLEXION, matching the angles in
  cad/poses.py, so a pose read off one of those scenes
  can be commanded here unchanged. Hip flexion swings the thigh forward; knee
  flexion folds the shin back under it; and because those are opposite senses
  in the sagittal plane, the two joints carry opposite axis vectors. A positive
  wheel angle rolls the robot forward.

  ACTUATOR. {actuator["model"]}, {actuator["gear_ratio"]:.0f}:1. The effort limits below are the
  {actuator["peak_torque_nm"]} Nm PEAK. The {actuator["continuous_torque_nm"]} Nm continuous rating is thermal rather than a
  hard ceiling, so it cannot be expressed as a URDF limit; it is a cost term in
  the Isaac Lab config instead.

  WHAT IS DRAWN. Everything the robot is made of, not just the printed parts.
  The printed pieces are their exported meshes, as they would be printed with
  their arrises broken at 0.5 mm; the actuators, wheels,
  bearings, boards and power entry are the primitives simulation/robot.py gives
  them, and each of those primitives is the part's real envelope -- it is the
  SAME solid its mass and inertia were computed from, so what you see is what
  is being integrated. Two are approximations and say so where they appear: the
  wheel's urethane is an annulus drawn as a full cylinder, because a URDF has
  no tube, and the wiring has mass but no body and so is not drawn at all.

  WHAT IS NOT MEASURED. The wheels have never been weighed, the capacitor bank
  has never been sized, the actuator's velocity limit and rotor inertia have
  never been recorded, and hip pitch has no established travel. Run
  simulation/check_model.py for the current tally of what is measured and what
  is not.
""")
        + f"""
<robot name="{ROBOT_NAME}">

  {palette}
{materials_block(materials)}"""
    )


def inertial_block(mass_kg: float, com_m: np.ndarray, tensor: np.ndarray) -> str:
    ixx, iyy, izz = tensor[0, 0], tensor[1, 1], tensor[2, 2]
    ixy, ixz, iyz = tensor[0, 1], tensor[0, 2], tensor[1, 2]
    return f"""    <inertial>
      <origin xyz="{vec(com_m)}" rpy="0 0 0"/>
      <mass value="{mass_kg:.6f}"/>
      <inertia ixx="{ixx:.9e}" ixy="{ixy:.9e}" ixz="{ixz:.9e}"
               iyy="{iyy:.9e}" iyz="{iyz:.9e}" izz="{izz:.9e}"/>
    </inertial>
"""


def primitive(shape: str, dims) -> tuple[str, tuple[float, float, float]]:
    """A primitive's URDF geometry, and the rpy that lays it in the ROS frame.

    One function for both visuals and collisions, because a bought part is
    drawn as exactly the solid its inertia was integrated from -- if the two
    ever came from different code they would drift, and a picture that
    disagrees with the physics is worse than no picture.
    """
    if shape == "box":
        # A box axis-aligned in the CAD frame is still axis-aligned in the ROS
        # frame; the quarter turn only swaps which extent is which.
        size = (dims[1] / 1000.0, dims[0] / 1000.0, dims[2] / 1000.0)
        return f'<box size="{vec(size)}"/>', (0.0, 0.0, 0.0)
    if shape in ("cylinder_x", "tube_x"):
        # A URDF has no annulus, so a tube is drawn at its outer diameter and
        # looks solid. Only the wheel's urethane is one, and its inertia is
        # still the annulus's; the bore is a hub, not a hole through the robot.
        diameter, length = (dims[0], dims[2]) if shape == "tube_x" else dims
        geometry = (
            f'<cylinder radius="{diameter / 2000.0:.6f}"'
            f' length="{length / 1000.0:.6f}"/>'
        )
        return geometry, rpy_from_axis_x()
    raise ValueError(f"unknown shape {shape!r}")


def slug(label: str) -> str:
    """A label like "hip pitch actuator, right" as an XML-safe name."""
    return "".join(c if c.isalnum() else "_" for c in label.lower()).strip("_")


def is_drawn(solid) -> bool:
    """Has this solid a body to draw? A fastener set and the wiring have not."""
    return solid.draw and solid.shape != "point"


def visual_block(solid, grams: float) -> str:
    """One solid drawn, with what it is and where its mass came from beside it.

    A printed piece is its exported mesh; everything bought is the primitive
    robot.py gives it. Both carry a comment naming the part, its mass and its
    provenance, because the person who opens this file in a simulator is
    exactly the person who needs to know that the wheels have never been
    weighed.
    """
    origin = ros_point(solid.at) / 1000.0
    note = " ".join(solid.note.split())
    label = comment(f" {solid.label} — {grams:.1f} g, {solid.source}: {note} ")

    if solid.shape == "mesh":
        geometry = (
            f'<mesh filename="meshes/{solid.piece}.stl" scale="0.001 0.001 0.001"/>'
        )
        # The mesh files are still in the CAD's frame, so each one is turned
        # here rather than re-exported.
        rpy = (0.0, 0.0, -1.5707963268)
    else:
        geometry, rpy = primitive(solid.shape, solid.dims)

    return f"""    {label}
    <visual name="{slug(solid.label)}">
      <origin xyz="{vec(origin)}" rpy="{vec(rpy)}"/>
      <geometry>
        {geometry}
      </geometry>
      <material name="{solid.material}"/>
    </visual>
"""


def collision_block(shape: str, dims, centre) -> str:
    origin = ros_point(centre) / 1000.0
    geometry, rpy = primitive(shape, dims)
    return f"""    <collision>
      <origin xyz="{vec(origin)}" rpy="{vec(rpy)}"/>
      <geometry>
        {geometry}
      </geometry>
    </collision>
"""


def joint_block(joint) -> str:
    origin = ros_point(joint.origin) / 1000.0
    axis = ros_point(joint.axis)
    limit = ""
    if joint.kind == "revolute":
        limit = (
            f'    <limit lower="{np.deg2rad(joint.lower):.9g}" '
            f'upper="{np.deg2rad(joint.upper):.9g}" '
            f'effort="{joint.effort}" velocity="{joint.velocity}"/>\n'
        )
    else:
        limit = f'    <limit effort="{joint.effort}" velocity="{joint.velocity}"/>\n'

    # Damping and friction are zero because they have never been measured on
    # this actuator. See ACTUATOR in simulation/robot.py.
    return f"""  {comment(" " + joint.note + " ")}
  <joint name="{joint.name}" type="{joint.kind}">
    <parent link="{joint.parent}"/>
    <child link="{joint.child}"/>
    <origin xyz="{vec(origin)}" rpy="0 0 0"/>
    <axis xyz="{vec(axis)}"/>
{limit}    <dynamics damping="{robot_model.ACTUATOR["damping_nm_s_rad"]}" friction="{robot_model.ACTUATOR["friction_nm"]}"/>
  </joint>
"""


def stale_pieces(pieces: set[str]) -> list[tuple[str, str, float]]:
    """Which exported meshes are older than the CAD they were exported from.

    This is the one thing in the pipeline that cannot be recomputed for free.
    Dimensions are re-read from cad/ on every build, so the joint origins are
    never stale -- but the meshes are exported output, and nothing else would
    notice a limb that changed shape after it was last exported. The result is a
    URDF whose kinematics have moved and whose geometry has not, which is worse
    than either being wrong on its own.

    Staleness is decided the way `make` decides it: a piece is stale if any file
    in cad/ is newer than its STL. Which file a piece comes from is the
    `[[printed.piece]]` register in tools/mass_budget.toml, so this follows the
    same register the exporter does -- see cad.dimensions.closure for why the
    dependency set is the whole package now that exporting is free.

    A fresh `git checkout` rewrites every mtime at once and can make this fire
    spuriously, which is why it names the offending file and why it is a
    stop-and-look rather than a silent decision.
    """
    # A `[[printed.piece]]` names the export; the FILE it comes from is on the
    # `[[printed]]` entry above it, which is how tools/export.py reads it too.
    origin = {
        piece["name"]: part["file"]
        for part in robot_model.budget()["printed"]
        for piece in part.get("piece", [])
    }
    stale = []
    for piece in sorted(pieces):
        mesh = RAW_MESHES / f"{piece}.stl"
        if not mesh.exists() or piece not in origin:
            continue
        exported = mesh.stat().st_mtime
        for source in closure(origin[piece]):
            age = source.stat().st_mtime - exported
            if age > GRACE_SECONDS:
                stale.append((piece, source.name, age))
                break
    return stale


def rewrite_meshes(pieces: set[str], meshes: MeshLibrary) -> list[tuple]:
    """Write each resolved piece into simulation/urdf/meshes as binary STL.

    What goes out is the RESOLVED solid, not the raw export: the shells have
    been unioned and the cavities subtracted, so the file holds one closed body
    with no internal faces. That is smaller, it renders without z-fighting
    where two shells used to overlap, and it is the same solid the inertia was
    integrated from -- which matters, because a collision mesh that disagrees
    with the inertia is a robot the simulator cannot be right about.
    """
    URDF_MESHES.mkdir(parents=True, exist_ok=True)
    written = []
    for piece in sorted(pieces):
        facts = meshes.properties(piece)
        source = RAW_MESHES / f"{piece}.stl"
        target = URDF_MESHES / f"{piece}.stl"
        target.write_bytes(trimesh.exchange.stl.export_stl(facts.solid))
        written.append(
            (
                piece,
                facts.shells,
                facts.triangles,
                source.stat().st_size,
                target.stat().st_size,
                facts.summed_grams - facts.grams,
            )
        )
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=URDF_DIR / f"{ROBOT_NAME}.urdf",
        help="where to write the URDF (default: simulation/urdf/wheeled_biped.urdf)",
    )
    parser.add_argument(
        "--allow-stale",
        action="store_true",
        help="build anyway when a mesh is older than the KCL it came from."
        " Use it to look at a work in progress, never to produce a URDF anyone"
        " is going to simulate.",
    )
    args = parser.parse_args()

    links, joints, dimensions = robot_model.build()
    density = robot_model.budget()["material"]["density"]
    meshes = MeshLibrary(RAW_MESHES, density)

    pieces = {
        solid.piece
        for link in links.values()
        for solid in link.solids
        if solid.shape == "mesh"
    }
    stale = stale_pieces(pieces)
    if stale:
        print("STALE MESHES", file=sys.stderr)
        for piece, source, age in stale:
            print(
                f"  {piece:<22} was exported before {source} changed"
                f" ({age / 60:.0f} min)",
                file=sys.stderr,
            )
        names = ",".join(sorted({piece for piece, _, _ in stale}))
        print(
            "\nThe kinematics in this build would be current and the geometry would not."
            "\nRe-export just these. It used to run on the engine and spend "
            "credits; since the build123d migration it is a local OCCT call and "
            "costs nothing but a few seconds:\n\n"
            f"    uv run tools/export.py --format stl --out simulation/meshes --pieces {names}"
            "\n\nor pass --allow-stale to build against the meshes as they are.",
            file=sys.stderr,
        )
        if not args.allow_stale:
            return 1
        print("", file=sys.stderr)

    try:
        written = rewrite_meshes(pieces, meshes)
    except FileNotFoundError as exc:
        print(exc, file=sys.stderr)
        return 1

    # Only the colours the robot actually uses are declared, and they come out
    # of the KCL palette rather than out of this file.
    palette = load_colors()
    used = {
        solid.material
        for link in links.values()
        for solid in link.solids
        if is_drawn(solid)
    }
    missing = sorted(used - set(palette))
    if missing:
        print(
            "these colours are named in simulation/robot.py but are in no KCL file: "
            + ", ".join(missing),
            file=sys.stderr,
        )
        return 1

    body = [header(dimensions, {name: palette[name] for name in used})]
    rows = []
    problems = []
    drawn = {"mesh": 0, "primitive": 0}

    # base_link first, then the rest in the order the joints reach them, so the
    # file reads down the robot rather than alphabetically.
    ordered = ["base_link"] + [joint.child for joint in joints]

    for name in ordered:
        link = links[name]
        try:
            grams, centre_mm, tensor_g_mm2 = link_properties(link.solids, meshes)
        except FileNotFoundError as exc:
            print(exc, file=sys.stderr)
            return 1

        mass_kg, com_m, tensor = to_si(grams, centre_mm, tensor_g_mm2)
        ok, why = is_plausible(tensor)
        if not ok:
            problems.append(f"{name}: {why}")

        body.append(f'\n  <link name="{name}">\n')
        body.append(inertial_block(mass_kg, com_m, tensor))
        for solid in link.solids:
            if not is_drawn(solid):
                continue
            weight = (
                meshes.properties(solid.piece).grams
                if solid.shape == "mesh"
                else solid.grams
            )
            drawn["mesh" if solid.shape == "mesh" else "primitive"] += 1
            body.append(visual_block(solid, weight))
        for shape, dims, centre in link.collisions:
            body.append(collision_block(shape, dims, centre))
        body.append("  </link>\n")

        rows.append((name, grams, com_m, np.linalg.eigvalsh(tensor)))

    body.append("\n")
    for joint in joints:
        body.append(joint_block(joint))
    body.append("\n</robot>\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(body), encoding="utf-8", newline="\n")

    # ---- what was written -------------------------------------------------
    print("meshes, resolved from their exported shells")
    overlap = 0.0
    for piece, shells, faces, ascii_bytes, binary_bytes, double_counted in written:
        overlap += double_counted
        print(
            f"  {piece:<22} {shells:2d} shells -> {faces:6d} triangles   "
            f"{ascii_bytes / 1024:6.0f} KB ascii -> {binary_bytes / 1024:5.0f} KB binary"
            f"   overlap resolved {double_counted:+5.2f} g"
        )
    print(
        f"  Resolving the overlaps takes {overlap:.1f} g off the pieces as exported, before\n"
        "  the counts the robot carries. tools/mass.py keeps that mass on purpose, because\n"
        "  counting an overlap twice errs upward against a ceiling; a dynamics model wants\n"
        "  the real body instead."
    )

    print("\nlinks")
    print(
        f"  {'link':<14} {'mass g':>8}   "
        f"{'centre of mass, m (x fwd, y left, z up)':<38} principal moments, kg m2"
    )
    total = 0.0
    for name, grams, com, moments in rows:
        total += grams
        com_text = f"{com[0]:+.4f} {com[1]:+.4f} {com[2]:+.4f}"
        moment_text = "  ".join(f"{m:.3e}" for m in moments)
        print(f"  {name:<14} {grams:8.1f}   {com_text:<38} {moment_text}")
    print(f"  {'TOTAL':<14} {total:8.1f}")

    where = args.out
    if where.is_relative_to(HERE.parent):
        where = where.relative_to(HERE.parent)
    print(
        f"\n{where} written, {len(joints)} joints, "
        f"{drawn['mesh']} printed meshes and {drawn['primitive']} bought parts drawn."
    )

    if problems:
        print("\nIMPLAUSIBLE INERTIA:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
